/* 语言注册表：新增语言的唯一入口——①在 I18N 加字典 ②在这里登记
   ③给 LOG_PATTERNS 补该语言的日志模板 ④加 README.<码>.md */
const LANGS = { zh: "中文", en: "English", ru: "Русский", es: "Español",
                pt: "Português (BR)", tr: "Türkçe", de: "Deutsch", fr: "Français" };
function detectInitialLang() {
  /* 优先级：用户手动选择（记住）> 浏览器语言 > 默认中文 */
  try {
    const saved = localStorage.getItem("rps-lang");
    if (saved && I18N[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.language || "").toLowerCase();
  for (const code of Object.keys(LANGS)) {
    if (nav.startsWith(code)) return code;
  }
  return "zh";
}
let LANG = detectInitialLang();

function t(key) { return (I18N[LANG] && I18N[LANG][key]) ?? key; }
function tf(key, vars) {
  let s = t(key);
  for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}
function esc(s) {
  /* 审核修复（中-30）：引号也得转义——esc 用在 HTML 属性上下文
     （title="${esc(p)}" 等），不转引号会属性逃逸 */
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}
function fmtSize(b) {
  if (b == null) return "";
  if (b < 1024) return Math.max(0, Math.round(b)) + " B";
  return b >= 1048576 ? (b / 1048576).toFixed(1) + " MB" : Math.round(b / 1024) + " KB";
}

